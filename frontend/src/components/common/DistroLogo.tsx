// matchDistro 根据 osRelease 字符串匹配发行版
// 不区分大小写，匹配第一个命中的 keywords
export function matchDistro(osRelease?: string): DistroMeta {
  if (!osRelease) {
    return DISTROS[DISTROS.length - 1]; // 默认 Linux
  }
  const lower = osRelease.toLowerCase();
  for (const d of DISTROS) {
    if (d.name === "Linux") continue; // 跳过 fallback
    for (const kw of d.keywords) {
      if (lower.includes(kw)) {
        return d;
      }
    }
  }
  return DISTROS[DISTROS.length - 1];
}

interface DistroLogoProps {
  osRelease?: string;
  size?: number;
  className?: string;
}

export function DistroLogo({
  osRelease,
  size = 24,
  className,
}: DistroLogoProps) {
  const meta = matchDistro(osRelease);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      className={className}
      fill={meta.color}
      role="img"
      aria-label={meta.name}
    >
      <path d={meta.path} />
    </svg>
  );
}
